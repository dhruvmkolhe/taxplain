import * as React from "react";
import { cn } from "@/src/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { interactive?: boolean }
>(({ className, interactive, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded border border-gray-200 dark:border-[#2a2a2a] bg-white dark:bg-[#1a1a1a] text-[#111111] dark:text-[#f2f2f2] transition-all duration-150 ease-out",
      interactive &&
        "hover:border-gray-400 dark:hover:border-[#404040] cursor-pointer active:scale-[0.995]",
      className
    )}
    {...props}
  />
));
Card.displayName = "Card";

